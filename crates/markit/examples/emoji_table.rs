//! Regenerates `src/github/emoji_table.rs` from the emojis crate's copy of
//! GitHub's gemoji shortcodes: `cargo run -p markit --example emoji_table`.
use std::fmt::Write;

fn main() {
    let mut pairs: Vec<(&str, &str)> = emojis::iter()
        .flat_map(|emoji| emoji.shortcodes().map(move |code| (code, emoji.as_str())))
        .collect();
    pairs.sort();
    pairs.dedup_by(|a, b| a.0 == b.0);
    let mut data = String::new();
    let mut starts = Vec::new();
    for (code, emoji) in &pairs {
        starts.push(data.len());
        writeln!(data, "{code} {emoji}").unwrap();
    }
    let mut out = String::from(
        "//! Generated by `cargo run -p markit --example emoji_table`; do not edit.\n\
         //! GitHub's gemoji shortcodes (MIT, GitHub Inc.) with their Unicode emoji\n\
         //! (Unicode License v3), as published by the emojis crate. One `code emoji`\n\
         //! line per shortcode, sorted by code.\n\n",
    );
    writeln!(
        out,
        "#[rustfmt::skip]\npub(super) const DATA: &str = {data:?};"
    )
    .unwrap();
    writeln!(
        out,
        "\n#[rustfmt::skip]\npub(super) const STARTS: [u32; {}] = {starts:?};",
        starts.len()
    )
    .unwrap();
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/src/github/emoji_table.rs");
    std::fs::write(path, out).unwrap();
    println!("{} shortcodes, {} bytes", pairs.len(), data.len());
}
